import { test, expect } from '@playwright/test';
test('payment, item budget, task and preview persistence', async ({ page }) => {
    const errors: string[] = [];
    page.on('pageerror', e => errors.push(e.message));
    await page.goto('/');
    await expect(page.getByRole('heading', { name: 'Your house, in perspective' })).toBeVisible();
    await expect(page.locator('.stat-primary')).toContainText('59,100,000');
    await page.screenshot({ path: 'outputs/web-overview.png', fullPage: true });
    await page.getByRole('button', { name: 'Budget items', exact: true }).click();
    await page.getByLabel('Filter by stage').selectOption({ label: 'Fence' });
    await page.getByLabel('Edit Fence labour', { exact: true }).click();
    let dialog = page.getByRole('dialog');
    await dialog.getByLabel('Estimated item budget').fill('1000000');
    await dialog.getByRole('button', { name: 'Save item' }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    let row = page.getByRole('row').filter({ has: page.getByText('Fence labour', { exact: true }) });
    await row.getByRole('button', { name: 'Pay', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel('Amount paid').fill('250000');
    await dialog.getByLabel('Payee / supplier').fill('Test supplier');
    await dialog.getByRole('button', { name: 'Save payment' }).click();
    await expect(row).toContainText('750,000');
    await page.getByRole('button', { name: 'Overview', exact: true }).click();
    await expect(page.locator('.stat-primary')).toContainText('59,350,000');
    await page.reload();
    await expect(page.locator('.stat-primary')).toContainText('59,350,000');
    await page.getByRole('button', { name: 'Project plan', exact: true }).click();
    await page.getByRole('button', { name: 'Add task', exact: true }).click();
    dialog = page.getByRole('dialog');
    await dialog.getByLabel(/^Task/).fill('Check fence delivery');
    await dialog.getByRole('button', { name: 'Save task' }).click();
    await page.getByRole('button', { name: 'Complete Check fence delivery', exact: true }).click();
    row = page.getByRole('row').filter({ has: page.getByText('Check fence delivery', { exact: true }) });
    await expect(row).toContainText('Done');
    await page.getByRole('button', { name: 'Payments', exact: true }).click();
    await page.getByLabel('Search records').fill('Test supplier');
    await expect(page.getByRole('row').filter({ hasText: 'Test supplier' })).toContainText('250,000');
    const download = page.waitForEvent('download');
    await page.getByRole('button', { name: 'Export CSV' }).click();
    await expect((await download).suggestedFilename()).toMatch(/Mabena-House-payments/);
    await page.getByLabel('Delete Fence labour', { exact: true }).click();
    await page.getByRole('dialog').getByRole('button', { name: 'Delete record' }).click();
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await expect(page.getByRole('row').filter({ hasText: 'Test supplier' })).toHaveCount(0);
    expect(errors).toEqual([]);
});
test('mobile layout, accessible modal and empty filters', async ({ page }) => {
    await page.setViewportSize({ width: 390, height: 844 });
    await page.goto('/');
    await expect(page.getByRole('heading', { name: 'Your house, in perspective' })).toBeVisible();
    await page.screenshot({ path: 'outputs/web-mobile.png', fullPage: true });
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(390);
    await page.getByRole('button', { name: 'Open menu' }).click();
    await page.getByRole('button', { name: 'Stages & budgets', exact: true }).click();
    await page.getByLabel('Search records').fill('nothing matches');
    await expect(page.getByText('No stages found. Add a stage or adjust your filters.')).toBeVisible();
    await page.getByRole('button', { name: 'Add stage' }).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    await page.keyboard.press('Escape');
    await expect(page.getByRole('dialog')).toHaveCount(0);
});
